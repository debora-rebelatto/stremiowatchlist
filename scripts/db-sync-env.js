const fs = require('fs');
const path = require('path');
const { parseEnvContent, isLocalSupabaseUrl } = require('../lib/envLoader');
const { ROOT_DIR, runCommand, assertLocalCliSafe, assertDockerRunning } = require('./db-guard');

function readOptionalEnv(fileName) {
  const filePath = path.join(ROOT_DIR, fileName);
  if (!fs.existsSync(filePath)) return {};
  return parseEnvContent(fs.readFileSync(filePath, 'utf8'));
}

function pickLocalApiKey(statusVars) {
  const candidates = ['SECRET_KEY', 'SERVICE_ROLE_KEY', 'PUBLISHABLE_KEY', 'ANON_KEY'];
  for (const keyName of candidates) {
    const val = statusVars[keyName];
    if (val && val.trim()) {
      return { keyName, value: val.trim() };
    }
  }
  return null;
}

function main() {
  assertLocalCliSafe('db:env');
  assertDockerRunning();

  const statusResult = runCommand('npx supabase status -o env');
  if (statusResult.status !== 0) {
    console.error(
      '[DB Sync] Failed to query local Supabase status. Run "npm run db:start" first.'
    );
    if (statusResult.stderr) {
      console.error(statusResult.stderr.trim());
    }
    process.exit(statusResult.status || 1);
  }

  const statusVars = parseEnvContent(statusResult.stdout || '');
  const apiUrl = (statusVars.API_URL || statusVars.SUPABASE_URL || '').trim();
  const pickedKey = pickLocalApiKey(statusVars);

  if (!apiUrl || !pickedKey) {
    console.error(
      '[DB Sync] Could not find local API_URL or API key in "supabase status -o env" output.'
    );
    process.exit(1);
  }

  if (!isLocalSupabaseUrl(apiUrl)) {
    console.error(
      `[DB Safety Guard] Refusing to write non-local Supabase URL (${apiUrl}) into .env.development.local.`
    );
    process.exit(1);
  }

  const existingDevEnv = readOptionalEnv('.env.development.local');
  const existingRootEnv = readOptionalEnv('.env');

  const tmdbKey = existingDevEnv.TMDB_API_KEY || existingRootEnv.TMDB_API_KEY || '';
  const adminEmail = existingDevEnv.ADMIN_EMAIL || existingRootEnv.ADMIN_EMAIL || '';

  const lines = [
    '# Auto-generated by scripts/db-sync-env.js for local Docker Supabase development.',
    '# Never commit this file to source control.',
    'APP_ENV=development',
    `SUPABASE_URL=${apiUrl}`,
    `SUPABASE_KEY=${pickedKey.value}`,
    'ENCRYPTION_KEY=local-dev-encryption-key-not-for-production',
    'VITE_POSTHOG_KEY=',
  ];

  if (tmdbKey) {
    lines.push(`TMDB_API_KEY=${tmdbKey}`);
  }
  if (adminEmail) {
    lines.push(`ADMIN_EMAIL=${adminEmail}`);
  }

  const outPath = path.join(ROOT_DIR, '.env.development.local');
  fs.writeFileSync(outPath, `${lines.join('\n')}\n`, 'utf8');

  console.log('✓ Updated .env.development.local for local Docker Supabase:');
  console.log(`  - SUPABASE_URL: ${apiUrl}`);
  console.log(`  - Key Type:     ${pickedKey.keyName}`);
  console.log(`  - PostHog:      disabled in development (VITE_POSTHOG_KEY=)`);
  console.log(`  - TMDB_API_KEY: ${tmdbKey ? 'preserved' : 'not set'}`);
  console.log(`  - ADMIN_EMAIL:  ${adminEmail ? 'preserved' : 'not set'}`);
}

main();
